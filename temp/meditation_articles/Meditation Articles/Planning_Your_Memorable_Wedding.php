					<p>
						You have finally said, Yes.  This is the start of your life as a couple.  And prior to that much-awaited big day, you, both the bride and groom have so many decisions to make and wedding-related tasks to complete.
<br><br>
Preparing for your wedding day need not be stressful.  On the other had, it should be fun and memorable.  And to do this, start off by putting together a wedding timetable.  
<br><br>
A short list of wedding-related tasks as well as a rough estimate of when the activities should be done follows. It presents tips and guidelines to keep you organized and help you think of all the matters that you must take into consideration in the course of planning for your big day.  Of course, these are mere suggestions.  All activities and schedule are still up to the couple to decide on depending on their priorities.
<br><br>
At the Time of the Engagement<br>
- You must tell your parents the happy news as soon as possible that is if they don't already know.  If you were having an engagement party, it would be good to keep your close friends and relatives in the know, too.<br>
- An organizer would be best to have in handy.  This will help you keep track of all the appointments, payments and other wedding-related activities that you must attend to.<br>
- Have your engagement photo taken.  This would be nice to have as a keepsake of this wonderful occasion.
<br><br>
6 to 12 Months In Advance Before the Big Day
<br><br>
- The couple should have already picked and decided on the wedding date.  Do the reservation for the venue where the ceremony and reception is to be held.<br>
- Set an appointment with the wedding officiant.<br>
- Establish a budget for the wedding, and try as much as possible to stick to it.
- Prepare a wedding guest list.  You wouldn't want to leave somebody uninvited unintentionally.<br>
- Look around for a photographer, florists, musicians, and a caterer.  Obtain estimates for these services.<br>
- Register at the bridal gift registry.<br>
- Pick a wedding dress and accessories to go with it.  If you are having a seamstress make you one, this is the time to have it arranged.  Several fittings may be required for this.<br>
- For the bride, select your bridesmaids.  Set a date for ordering dresses for them.
<br><br>
4 to 6 Months In Advance Before the Big Day<br>
- Have the invitations, stationeries, and thank you notes ordered.<br>
- The photographer, florist, musician, and caterer should have already been chosen. Go over details with each of these services to make sure that everything is as agreed upon.<br>
- For the groom, select attire.<br>
- Honeymoon reservations should be made already at this point.<br>
- Confirm the delivery of the bridal gown.
<br><br>
2 Months In Advance Before the Big Day
- Plan your rehearsal dinner.<br>
- If you are having out-of-town attendants, arrange for their lodging.<br>
- Make an appointment with your chosen photographer for the shooting of the bridal portrait.<br>
- Order the wedding cake.
<br><br>
1 Month In Advance Before the Big Day<br>
- The couple should decide on a wedding band set.<br>
- Mail the invitations.<br>
- Check the apparel for the wedding party.<br>
- The couple attends showers.
<br><br>
2 Weeks Before the Wedding<br>
- It is time to apply for marriage license and attend to other legal matters, especially for the bride - name and address changes on bank accounts and other official documents.<br>
- Plan a wedding hairstyle and make-up with your stylist.<br>
- Check with the caterer and the reception venue for last minute changes.<br>
<br><br>
1 Week Before the Wedding<br>
- Do your honeymoon packing.<br>
- Wrap gifts for the groom and attendants.<br>
- Schedule the wedding rehearsal.<br>
- Remind the wedding party of the exact time and place for the occasion.
<br><br>
On Wedding Day<br>
- Take breakfast!  Fainting on the aisle wouldn't be cool.<br>
- Have your hair and make-up done.<br>
- Shake off all your wedding details worries and enjoy your day.
